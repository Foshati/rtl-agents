/**
 * Main-process hook for chat surfaces that live in a cross-origin frame.
 *
 * Antigravity IDE does not render its agent chat in the workbench document. Its
 * bundled `agy` extension opens a webview whose only content is an iframe onto
 * the agent's local server (`http://127.0.0.1:<port>/c/<id>?extensionView=true…`),
 * and the page's files are embedded in the `agy` binary. Workbench CSS and JS
 * cannot cross that origin boundary, and there is no file on disk to patch.
 *
 * Electron's main process can reach any frame. A single line prepended to
 * `out/main.js` loads `rtl-agents-main.js` from the asset directory; it waits for
 * frames of the agent page to load and runs the same generated CSS and JS in them
 * that the workbench gets. The line is a dynamic `import()` with a `.catch`, so a
 * missing or broken hook can never stop the IDE from starting, and `out/main.js`
 * is not covered by the `product.json` checksums.
 */

import type { IdeInstallation } from './types'
import * as fs from 'node:fs/promises'
import * as path from 'node:path'
import { CSS_FILENAME, JS_FILENAME } from './content'
import { exists } from './utils'

export const MAIN_HOOK_FILENAME = 'rtl-agents-main.js'

const HOOK_MARK = '/* RTL-AGENTS-MAIN */'
const HOOK_LINE = /^\/\* RTL-AGENTS-MAIN \*\/[^\n]*\n/

export function mainEntryPath(installation: IdeInstallation): string {
  return path.join(installation.appRoot, 'out', 'main.js')
}

/**
 * Only hosts that embed the agent page get a main-process hook: today that is
 * Antigravity IDE, recognised by its bundled `agy` extension.
 */
export async function needsMainHook(installation: IdeInstallation): Promise<boolean> {
  return (await exists(path.join(installation.appRoot, 'extensions', 'agy')))
    && (await exists(mainEntryPath(installation)))
}

export function hookLine(installation: IdeInstallation): string {
  const outDir = path.dirname(mainEntryPath(installation))
  const rel = path.relative(outDir, path.join(installation.workbenchDir, MAIN_HOOK_FILENAME)).replace(/\\/g, '/')
  const spec = rel.startsWith('.') ? rel : `./${rel}`
  return `${HOOK_MARK}import(${JSON.stringify(spec)}).catch(function () {});\n`
}

export function stripMainHook(source: string): string {
  return source.replace(HOOK_LINE, '')
}

export function hasMainHook(source: string): boolean {
  return source.startsWith(HOOK_MARK)
}

/**
 * The module the hook line loads. It reads the assets from disk on every frame
 * load, so a settings change or an extension update reaches the next reload, and
 * deactivating — which deletes the assets — stops it without touching main.js.
 */
export function buildMainHook(): string {
  return `/* Generated by RTL Agents — do not edit by hand. */
/* Runs RTL Agents' CSS and JS in the agent chat frame, which workbench files cannot reach. */
import { app, webFrameMain } from 'electron';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = dirname(fileURLToPath(import.meta.url));
// Marked on the document, not the window: a window outlives the document that
// replaces it during navigation, and a window flag would then skip the new one.
const MARK = 'data-rtl-agents-frame';

// The agent page: served from loopback and opened as an extension view.
function isAgentPage(url) {
  try {
    const u = new URL(url);
    return (u.hostname === '127.0.0.1' || u.hostname === 'localhost')
      && u.searchParams.get('extensionView') === 'true';
  }
  catch {
    return false;
  }
}

function payload() {
  const css = readFileSync(join(DIR, ${JSON.stringify(CSS_FILENAME)}), 'utf8');
  const js = readFileSync(join(DIR, ${JSON.stringify(JS_FILENAME)}), 'utf8');
  return '(function () {\\n'
    + 'var root = document.documentElement;\\n'
    + 'if (!root || root.hasAttribute(' + JSON.stringify(MARK) + ')) { return; }\\n'
    + 'root.setAttribute(' + JSON.stringify(MARK) + ', "1");\\n'
    + 'try { delete window.__rtlAgents; } catch (e) {}\\n'
    + 'var s = document.createElement("style"); s.id = "rtl-agents-style"; s.textContent = '
    + JSON.stringify(css) + ';\\n'
    + '(document.head || root).appendChild(s);\\n'
    + js + '\\n})();';
}

function inject(frame) {
  if (!frame || frame.isDestroyed?.() || !isAgentPage(frame.url)) {
    return;
  }
  let code;
  try {
    code = payload();
  }
  catch {
    return; // assets gone: RTL Agents was deactivated
  }
  frame.executeJavaScript(code).catch(() => {});
}

function onFrame(_event, _isMainFrame, processId, routingId) {
  try {
    inject(webFrameMain.fromId(processId, routingId));
  }
  catch { /* frame went away */ }
}

try {
  app.on('web-contents-created', (_event, contents) => {
    // Navigate fires at commit, before the page's own scripts finish; load is
    // the fallback. The flag keeps it to one run per document.
    contents.on('did-frame-navigate', (event, url, code, status, isMainFrame, processId, routingId) =>
      onFrame(event, isMainFrame, processId, routingId));
    contents.on('did-frame-finish-load', (event, isMainFrame, processId, routingId) => {
      onFrame(event, isMainFrame, processId, routingId);
      // The page can swap its document right after load; the document mark makes
      // a second pass free when nothing changed.
      setTimeout(() => onFrame(event, isMainFrame, processId, routingId), 1500);
    });
  });
}
catch { /* never break the IDE */ }
`
}

/**
 * Write the hook module and prepend the hook line to `out/main.js`.
 * Returns true when anything on disk changed.
 */
export async function applyMainHook(installation: IdeInstallation, messages: string[]): Promise<boolean> {
  let changed = false

  const hookPath = path.join(installation.workbenchDir, MAIN_HOOK_FILENAME)
  const module = buildMainHook()
  const current = await fs.readFile(hookPath, 'utf-8').catch(() => undefined)
  if (current !== module) {
    await fs.writeFile(hookPath, module, 'utf-8')
    messages.push(`  ${MAIN_HOOK_FILENAME}: Written`)
    changed = true
  }

  const entry = mainEntryPath(installation)
  const source = await fs.readFile(entry, 'utf-8')
  const patched = hookLine(installation) + stripMainHook(source)
  if (patched !== source) {
    await fs.writeFile(entry, patched, 'utf-8')
    messages.push('  main.js: Agent frame hook added')
    changed = true
  }

  return changed
}

/**
 * Take the hook line out of `out/main.js` and delete the hook module.
 */
export async function removeMainHook(installation: IdeInstallation, messages: string[]): Promise<boolean> {
  let changed = false

  const entry = mainEntryPath(installation)
  const source = await fs.readFile(entry, 'utf-8').catch(() => undefined)
  if (source !== undefined && hasMainHook(source)) {
    await fs.writeFile(entry, stripMainHook(source), 'utf-8')
    messages.push('  main.js: Agent frame hook removed')
    changed = true
  }

  const hookPath = path.join(installation.workbenchDir, MAIN_HOOK_FILENAME)
  if (await exists(hookPath)) {
    await fs.unlink(hookPath).catch(() => {})
    messages.push(`  Deleted ${MAIN_HOOK_FILENAME}`)
    changed = true
  }

  return changed
}

/**
 * Whether the hook is in place and current — or not needed at all.
 */
export async function mainHookCurrent(installation: IdeInstallation): Promise<boolean> {
  if (!(await needsMainHook(installation))) {
    return true
  }
  const source = await fs.readFile(mainEntryPath(installation), 'utf-8').catch(() => '')
  const module = await fs.readFile(path.join(installation.workbenchDir, MAIN_HOOK_FILENAME), 'utf-8').catch(() => undefined)
  return source.startsWith(hookLine(installation)) && module === buildMainHook()
}
